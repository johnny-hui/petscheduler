package com.johnny.petscheduler.security.utils;

import com.johnny.petscheduler.security.jwt.TokenPair;
import com.johnny.petscheduler.security.jwt.TokenType;
import io.jsonwebtoken.Claims;
import io.jsonwebtoken.JwtException;
import io.jsonwebtoken.Jwts;
import lombok.Getter;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.PrivateKey;
import java.security.PublicKey;
import java.util.Date;
import java.util.HexFormat;

import static com.johnny.petscheduler.security.configs.SecurityConstants.*;

@Component
public final class JWTUtil
{
    @Getter
    @Value("${jwt.access.expiration.time}")
    private long jwtAccessExpirationTimeMs;

    @Getter
    @Value("${jwt.refresh.expiration.time}")
    private long jwtRefreshExpirationTimeMs;

    private final PrivateKey privateKey;
    private final PublicKey publicKey;

    @Autowired
    public JWTUtil(PrivateKey privateKey, PublicKey publicKey)
    {
        this.privateKey = privateKey;
        this.publicKey = publicKey;
    }

    /**
     * Generates and returns JWT access & refresh token.
     *
     * @implNote JWT Payload Section
     * <code>
     *     {
     *      *   "sub": "johnny@example.com",
     *      *   "token_type": "refresh",
     *      *   "iat": 1791350000,
     *      *   "exp": 1793942000
     *      * }
     * </code>
     *
     * @param email
     *      The subject for the JWT token (String)
     *
     * @return <code>TokenPair</code>
     *      A record that combines the two tokens
     */
    public TokenPair generateTokenPair(final String email) {
        return new TokenPair(
                generateToken(email, TokenType.ACCESS),
                generateToken(email, TokenType.REFRESH)
        );
    }

    /**
     * Verifies and Parses the given JWT token.
     *
     * @param token
     *      A String representing the JWT token
     *
     * @return <code>Claims</code>
     *      The claims inside the JWT
     */
    public Claims parseToken(final String token) throws JwtException
    {
        return Jwts.parser()
                .verifyWith(publicKey)
                .build()
                .parseSignedClaims(token)
                .getPayload();
    }

    /**
     * Parses JWT payload section for the subject which contains
     * the user's email.
     *
     * @param claims
     *      A Claims object containing metadata from JWT
     *
     * @return email
     *      A String for the user's email
     */
    public String getEmailFromToken(final Claims claims) {
        return claims.getSubject();
    }

    /**
     * Determines if a JWT token is a refresh token.
     *
     * @param claims
     *      A Claims object containing metadata from JWT
     *
     * @return <code>bool (T/F)</code>
     *      True if refresh; false otherwise
     */
    public boolean isTokenRefresh(final Claims claims) {
        return claims.get(TOKEN_TYPE_HEADER).equals(JWT_REFRESH);
    }

    /**
     * Hashes a JWT token using SHA-256 cryptographic hasher.
     *
     * @param token
     *      A String for the JWT token
     *
     * @return <code>hashedToken</code>
     *      A String containing the hashed JWT token
     */
    public String tokenHasher(final String token)
    {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(token.getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(hash);
        }
        catch (final NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 algorithm is unavailable", e);
        }
    }

    /**
     * Compares String hashes generated by SHA-256.
     *
     * @param hash1
     *      The first hash to be compared (String)
     *
     * @param hash2
     *      The second hash to be compared (String)
     *
     * @return bool (T/F)
     *      True if equal; false otherwise
     */
    public boolean areHashesEqual(final String hash1, final String hash2)
    {
        if (hash1 == null || hash2 == null) {
            return false;
        }
        return MessageDigest.isEqual(
                HexFormat.of().parseHex(hash1),
                HexFormat.of().parseHex(hash2)
        );
    }

    private String generateToken(final String email,
                                 final TokenType tokenType)
    {
        switch(tokenType)
        {
            case ACCESS -> {
                return Jwts.builder()
                        .subject(email)
                        .claim(TOKEN_TYPE_HEADER, JWT_ACCESS)
                        .issuedAt(new Date())
                        .expiration(new Date(System.currentTimeMillis() + jwtAccessExpirationTimeMs))
                        .signWith(privateKey, Jwts.SIG.ES256)
                        .compact();
            }
            case REFRESH -> {
                return Jwts.builder()
                        .subject(email)
                        .claim(TOKEN_TYPE_HEADER, JWT_REFRESH)
                        .issuedAt(new Date())
                        .expiration(new Date(System.currentTimeMillis() + jwtRefreshExpirationTimeMs))
                        .signWith(privateKey, Jwts.SIG.ES256)
                        .compact();
            }
            default -> {
                return null;
            }
        }
    }
}
